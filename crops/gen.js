const wm = '每张图右下角 #49 卡有“洛谷”水印，不影响文字读取。';

function emit(b) {
  const flat = [];
  for (const row of b.rows) for (const c of row) flat.push(c);
  const lines = [];
  lines.push('{');
  lines.push(`  "space": ${b.space},`);
  lines.push(`  "type": "${b.type}",`);
  lines.push(`  "ac": ${b.ac},`);
  lines.push('  "cells": [');
  flat.forEach((c, i) => {
    lines.push(`    {"id": ${i + 1}, "label": "${c[0]}", "space": ${c[1]}, "size": "${c[2]}"}${i < 48 ? ',' : ''}`);
  });
  lines.push('  ],');
  const note = (mixedNotes[b.space] ? mixedNotes[b.space] + '\n' : '') + wm;
  lines.push(`  "notes": ${JSON.stringify(note)}`);
  lines.push('}');
  return lines.join('\n');
}

